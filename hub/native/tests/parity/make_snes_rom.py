#!/usr/bin/env python3
"""Gera uma ROM LoROM de teste (128 KB) com cabeçalho válido, dados aleatórios, um prólogo que prepara PPU/DMA,
sobe um programa para o SPC700 pelo IPL (protocolo das portas 2140-2143) e entra num laço."""
import random, sys
seed, out = int(sys.argv[1]), sys.argv[2]
rnd = random.Random(seed)
rom = bytearray(rnd.randrange(256) for _ in range(0x20000))
code = bytearray()
def lda_i(v): code.extend([0xA9, v])
def sta(a): code.extend([0x8D, a & 255, a >> 8])
def w(a, v): lda_i(v); sta(a)
code.extend([0x18, 0xFB, 0xE2, 0x20, 0xC2, 0x10])           # CLC XCE; SEP #$20; REP #$10
for a, v in [(0x2100, 0x80), (0x2115, 0x80), (0x2116, 0), (0x2117, 0)]: w(a, v)
def dma(ch, ctl, breg, src, size, bank=0):
    b = 0x4300 + ch * 16
    for a, v in [(b, ctl), (b + 1, breg), (b + 2, src & 255), (b + 3, src >> 8), (b + 4, bank), (b + 5, size & 255), (b + 6, size >> 8)]: w(a, v)
    w(0x420B, 1 << ch)
dma(0, 0x01, 0x18, 0x9000, 0x4000)                           # VRAM <- ROM
w(0x2121, 0); dma(1, 0x00, 0x22, 0xB000, 0x200)              # CGRAM <- ROM
w(0x2102, 0); w(0x2103, 0); dma(2, 0x00, 0x04, 0xA000, 0x220)  # OAM <- ROM
modo = rnd.choice([0, 1, 1, 1, 2, 3, 4, 5, 7])
for a, v in [(0x2101, 0x62), (0x2105, modo), (0x2107, 0x04), (0x2108, 0x08), (0x2109, 0x0C), (0x210B, 0x21), (0x210C, 0x03),
             (0x212C, 0x17), (0x212D, 0x02), (0x2130, 0x02), (0x2131, 0x21), (0x2100, 0x0F), (0x4200, 0x81)]: w(a, v)
# --- upload do SPC ---
TAB = 0x8800
spc = bytearray(0x300)
def spc_w(off, bs): spc[off:off + len(bs)] = bytes(bs)
dsp = [(0x0C, 0x7F), (0x1C, 0x7F), (0x2C, 0), (0x3C, 0), (0x6C, 0x00), (0x5D, 0x03), (0x6D, 0x10), (0x7D, 0x01), (0x0D, 0x40), (0x0F, 0x7F), (0x4D, 0x01), (0x2D, 0x02),
       (0x00, 0x7F), (0x01, 0x7F), (0x02, 0x00), (0x03, 0x10), (0x04, 0x00), (0x05, 0xFF), (0x06, 0xE0), (0x07, 0x7F),
       (0x10, 0x60), (0x11, 0x60), (0x12, 0x00), (0x13, 0x08), (0x14, 0x01), (0x15, 0xFF), (0x16, 0xE0), (0x17, 0x7F), (0x4C, 0x03)]
prog = bytearray()
for r, v in dsp: prog += bytes([0x8F, r, 0xF2, 0x8F, v, 0xF3])
prog += bytes([0x2F, 0xFE])
spc_w(0, prog)
spc_w(0x100, [0x00, 0x04, 0x00, 0x04, 0x10, 0x04, 0x10, 0x04])   # diretório em $0300
brr = lambda hdr: bytes([hdr] + [rnd.randrange(256) for _ in range(8)])
spc_w(0x200, brr(0xC3))                                        # amostra 0: fim + loop
spc_w(0x210, brr(0xB3))                                        # amostra 1
rom[TAB - 0x8000:TAB - 0x8000 + 0x300] = spc
def waitp(port, val): code.extend([0xAD, port & 255, port >> 8, 0xC9, val, 0xD0, 0xF9])
waitp(0x2140, 0xAA)
w(0x2141, 1); w(0x2142, 0x00); w(0x2143, 0x02); w(0x2140, 0xCC); waitp(0x2140, 0xCC)
code.extend([0xA2, 0x00, 0x00])                                 # LDX #0
loop = len(code)
code.extend([0xBD, TAB & 255, TAB >> 8, 0x8D, 0x41, 0x21, 0x8A, 0x8D, 0x40, 0x21, 0xCD, 0x40, 0x21, 0xD0, 0xFB, 0xE8, 0xE0, 0x00, 0x03])
code.extend([0xD0, (loop - (len(code) + 2)) & 255])
w(0x2141, 0); w(0x2142, 0x00); w(0x2143, 0x02); w(0x2140, 0x02)  # executar em $0200
main = len(code)
code.extend([0xAD, 0x40, 0x21, 0x49, 0x55, 0x8D, 0x41, 0x21, 0x80, 0xF6])
rom[0:len(code)] = code
rom[0xF00] = 0x40                                                # RTI em $8F00
# cabeçalho LoROM em $7FC0
rom[0x7FC0:0x7FC0 + 21] = b'PARIDADE NATIVA     '[:21].ljust(21)
rom[0x7FD5] = 0x20; rom[0x7FD6] = 0x00; rom[0x7FD7] = 0x08; rom[0x7FD8] = 0x00; rom[0x7FD9] = 0x01
rom[0x7FDC:0x7FE0] = bytes([0xFF, 0xFF, 0x00, 0x00])           # complemento + checksum = $FFFF
for v in (0x7FEA, 0x7FEE, 0x7FFA, 0x7FFE): rom[v:v + 2] = bytes([0x00, 0x8F])
rom[0x7FFC:0x7FFE] = bytes([0x00, 0x80])
open(out, 'wb').write(rom)
